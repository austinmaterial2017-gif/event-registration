import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");

const publicFiles = [
  "apps-script/appsscript.json",
  "apps-script/Repository.gs",
  "apps-script/RegistrationService.gs",
  "apps-script/TicketService.gs",
  "apps-script/AttendanceService.gs",
  "apps-script/Code.gs"
];
const staffFiles = [
  "staff-apps-script/appsscript.json",
  "staff-apps-script/Repository.gs",
  "staff-apps-script/AttendanceService.gs",
  "staff-apps-script/AdminService.gs",
  "staff-apps-script/Code.gs",
  "staff-apps-script/Admin.html",
  "staff-apps-script/AdminScript.html"
];

function normalized(text) {
  return text.replace(/\r\n/g, "\n");
}

async function buildBundle(fileNames) {
  const sections = [];
  for (const fileName of fileNames) {
    const source = normalized(await readFile(join(root, fileName), "utf8")).trimEnd();
    sections.push(`===== ${fileName} =====\n${source}`);
  }
  return `${sections.join("\n\n")}\n`;
}

function assertRedacted(bundle, label) {
  const forbidden = [
    { name: "email address", pattern: /\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/i },
    { name: "private key", pattern: /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/i },
    { name: "assigned credential", pattern: /\b(?:password|api[_-]?key|client[_-]?secret)\s*[:=]\s*["'][^"']+["']/i },
    { name: "hard-coded opaque identifier", pattern: /["'][A-Za-z0-9_-]{32,}["']/ }
  ];
  for (const entry of forbidden) {
    if (entry.pattern.test(bundle)) {
      throw new Error(`${label} contains a possible ${entry.name}.`);
    }
  }
}

function generatedSourceFor(publicBundle, staffBundle) {
  return [
    "/** Generated by scripts/build-admin-source-bundles.mjs. Do not edit manually. */",
    `var PUBLIC_BACKEND_SOURCE_BUNDLE_ = ${JSON.stringify(publicBundle)};`,
    `var STAFF_ADMIN_SOURCE_BUNDLE_ = ${JSON.stringify(staffBundle)};`,
    ""
  ].join("\n");
}

async function verifyOrWrite(path, expected) {
  if (!checkOnly) {
    await writeFile(path, expected, "utf8");
    return;
  }
  let actual;
  try {
    actual = normalized(await readFile(path, "utf8"));
  } catch {
    throw new Error(`Generated source bundle is missing: ${path}`);
  }
  if (actual !== expected) {
    throw new Error(`Generated source bundle is stale: ${path}`);
  }
}

const publicBundle = await buildBundle(publicFiles);
const staffCoreBundle = await buildBundle(staffFiles);
const copiedBundleSource = generatedSourceFor(publicBundle, staffCoreBundle);
const staffBundle = `${staffCoreBundle}\n===== staff-apps-script/SourceBundles.gs =====\n${copiedBundleSource}`;
assertRedacted(publicBundle, "Public bundle");
assertRedacted(staffBundle, "Staff bundle");
if (!checkOnly) await mkdir(join(root, "source-bundles"), { recursive: true });

const generatedSource = generatedSourceFor(publicBundle, staffBundle);

await verifyOrWrite(join(root, "source-bundles", "public-backend.txt"), publicBundle);
await verifyOrWrite(join(root, "source-bundles", "staff-admin.txt"), staffBundle);
await verifyOrWrite(join(root, "staff-apps-script", "SourceBundles.gs"), generatedSource);
