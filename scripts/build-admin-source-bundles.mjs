import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const rootOption = process.argv.indexOf("--root");
if (rootOption !== -1 && !process.argv[rootOption + 1]) {
  throw new Error("Bundle generation failed: --root requires a directory.");
}
const root = rootOption === -1
  ? join(dirname(fileURLToPath(import.meta.url)), "..")
  : resolve(process.argv[rootOption + 1]);
const checkOnly = process.argv.includes("--check");

const publicFiles = [
  "apps-script/appsscript.json",
  "apps-script/Repository.gs",
  "apps-script/ReadableViews.gs",
  "apps-script/RegistrationService.gs",
  "apps-script/TicketService.gs",
  "apps-script/AttendanceService.gs",
  "apps-script/InternalGateway.gs",
  "apps-script/InternalMutationService.gs",
  "apps-script/SwitchProbeService.gs",
  "apps-script/Code.gs"
];
const staffFiles = [
  "staff-apps-script/appsscript.json",
  "staff-apps-script/Repository.gs",
  "staff-apps-script/InternalClient.gs",
  "staff-apps-script/AttendanceService.gs",
  "staff-apps-script/AdminService.gs",
  "staff-apps-script/Code.gs",
  "staff-apps-script/StaffCheckIn.html",
  "staff-apps-script/Admin.html",
  "staff-apps-script/AdminScript.html"
];

function normalized(text) {
  return text.replace(/\r\n/g, "\n");
}

async function buildBundle(fileNames) {
  const sections = [];
  for (const fileName of fileNames) {
    const source = normalized(await readFile(join(root, fileName), "utf8")).trimEnd();
    sections.push(`===== ${fileName} =====\n${source}`);
  }
  return `${sections.join("\n\n")}\n`;
}

function assertRedacted(bundle, label) {
  const forbidden = [
    {
      name: "deployed Apps Script URL",
      pattern: /https:\/\/script\.google\.com\/macros\/s\/[A-Za-z0-9_-]{10,}\/exec/i
    },
    {
      name: "concrete Google Sheet URL",
      pattern: /https:\/\/docs\.google\.com\/spreadsheets\/d\/1[A-Za-z0-9_-]{20,}/i
    },
    { name: "Google Sheet ID", pattern: /["']1[A-Za-z0-9_-]{20,}["']/ },
    { name: "email address", pattern: /\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/i },
    { name: "private key", pattern: /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/i },
    { name: "assigned credential", pattern: /\b(?:password|api[_-]?key|client[_-]?secret)\s*[:=]\s*["'][^"']+["']/i },
    {
      name: "participant phone",
      pattern: /\b(?:participant|attendee|registrant)?(?:phone|mobile|telephone|tel|contact)(?:number)?\s*[:=]\s*["']\+?\d[\d ()-]{7,}\d["']/i
    },
    { name: "hard-coded opaque identifier", pattern: /["'][A-Za-z0-9_-]{32,}["']/ }
  ];
  for (const entry of forbidden) {
    if (entry.pattern.test(bundle)) {
      throw new Error(`${label} contains a possible ${entry.name}.`);
    }
  }
  const assignedPrivateValue =
    /\b((?:[A-Z][A-Z0-9_]*SHARED_SECRET)|(?:[A-Z][A-Z0-9_]*ALLOWLIST)|(?:[A-Z][A-Z0-9_]*SPREADSHEET_ID)|PUBLIC_BACKEND_URL)\s*=\s*["']([^"']*)["']/g;
  for (const match of bundle.matchAll(assignedPrivateValue)) {
    if (match[1] === match[2]) continue;
    const name = match[1].includes("SHARED_SECRET")
      ? "assigned shared secret"
      : match[1].includes("ALLOWLIST")
        ? "assigned allowlist"
        : "assigned private configuration";
    throw new Error(`${label} contains a possible ${name}.`);
  }
}

function selfStableGeneratedSourceFor(publicBundle, staffCoreBundle) {
  const placeholder = "__SELF_SOURCE_JSON__";
  const template = [
    "/** Generated by scripts/build-admin-source-bundles.mjs. Do not edit manually. */",
    `var STAFF_ADMIN_SOURCE_TEMPLATE_ = ${placeholder};`,
    `var PUBLIC_BACKEND_SOURCE_BUNDLE_ = ${JSON.stringify(publicBundle)};`,
    `var STAFF_ADMIN_SOURCE_CORE_BUNDLE_ = ${JSON.stringify(staffCoreBundle)};`,
    "var STAFF_ADMIN_SOURCE_BUNDLE_ = STAFF_ADMIN_SOURCE_CORE_BUNDLE_ +",
    '  "\\n===== staff-apps-script/SourceBundles.gs =====\\n" +',
    "  STAFF_ADMIN_SOURCE_TEMPLATE_.replace(",
    `    ${JSON.stringify(placeholder)},`,
    "    JSON.stringify(STAFF_ADMIN_SOURCE_TEMPLATE_)",
    "  );",
    ""
  ].join("\n");
  return template.replace(placeholder, JSON.stringify(template));
}

async function verifyOrWrite(path, expected) {
  if (!checkOnly) {
    await writeFile(path, expected, "utf8");
    return;
  }
  let actual;
  try {
    actual = normalized(await readFile(path, "utf8"));
  } catch {
    throw new Error(`Generated source bundle is missing: ${path}`);
  }
  if (actual !== expected) {
    throw new Error(`Generated source bundle is stale: ${path}`);
  }
}

const publicBundle = await buildBundle(publicFiles);
const staffCoreBundle = await buildBundle(staffFiles);
const copiedBundleSource = selfStableGeneratedSourceFor(publicBundle, staffCoreBundle);
const staffBundle = `${staffCoreBundle}\n===== staff-apps-script/SourceBundles.gs =====\n${copiedBundleSource}`;
assertRedacted(publicBundle, "Public bundle");
assertRedacted(staffBundle, "Staff bundle");
if (!checkOnly) await mkdir(join(root, "source-bundles"), { recursive: true });

await verifyOrWrite(join(root, "source-bundles", "public-backend.txt"), publicBundle);
await verifyOrWrite(join(root, "source-bundles", "staff-admin.txt"), staffBundle);
await verifyOrWrite(join(root, "staff-apps-script", "SourceBundles.gs"), copiedBundleSource);
