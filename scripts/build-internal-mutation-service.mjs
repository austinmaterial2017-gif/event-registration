function runAdminMutationTransaction_(registry, spreadsheet, action, callback) {
  if (ADMIN_TRANSACTION_) return callback();
  ADMIN_TRANSACTION_ = {
    action: action,
    entries: [],
    sheets: [],
    seen: {}
  };
  try {
    return callback();
  } catch (error) {
    var failures = rollbackAdminMutationTransaction_();
    if (failures.length) {
      var integrityError = new Error('INTEGRITY_ERROR');
      integrityError.publicCode = 'INTEGRITY_ERROR';
      integrityError.cause = error;
      integrityError.rollbackFailures = failures;
      throw integrityError;
    }
    throw error;
  } finally {
    ADMIN_TRANSACTION_ = null;
  }
}

function journalAdminWrite_(sheet, rowNumber, columnCount, isAppend) {
  if (!ADMIN_TRANSACTION_) return;
  var sheetIndex = ADMIN_TRANSACTION_.sheets.indexOf(sheet);
  if (sheetIndex === -1) {
    ADMIN_TRANSACTION_.sheets.push(sheet);
    sheetIndex = ADMIN_TRANSACTION_.sheets.length - 1;
  }
  var key = sheetIndex + ':' + rowNumber;
  if (ADMIN_TRANSACTION_.seen[key]) return;
  ADMIN_TRANSACTION_.seen[key] = true;
  ADMIN_TRANSACTION_.entries.push({
    sheet: sheet,
    rowNumber: rowNumber,
    isAppend: isAppend === true,
    values: isAppend ? null :
      sheet.getRange(rowNumber, 1, 1, columnCount).getValues()[0]
  });
}

function rollbackAdminMutationTransaction_() {
  var transaction = ADMIN_TRANSACTION_;
  if (!transaction) return [];
  var failures = [];
  for (var index = transaction.entries.length - 1; index >= 0; index -= 1) {
    var entry = transaction.entries[index];
    try {
      if (entry.isAppend) {
        if (entry.sheet.getLastRow() >= entry.rowNumber) {
          entry.sheet.deleteRow(entry.rowNumber);
        }
      } else {
        entry.sheet.getRange(
          entry.rowNumber, 1, 1, entry.values.length
        ).setValues([entry.values]);
      }
    } catch (error) {
      failures.push(error);
    }
  }
  return failures;
}

