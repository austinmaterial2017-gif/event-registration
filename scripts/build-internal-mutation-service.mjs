function internalStaffCheckInLocked_(payload, actor) {
  var registry = getRegistrySpreadsheet_();
  requireNoSwitchMaintenance_(registry);
  if (!payload || typeof payload !== 'object' ||
      typeof payload.sessionId !== 'string' || !payload.sessionId.trim()) {
    adminError_('INVALID_REQUEST');
  }
  var route = requireAttendanceTicketRoute_(registry, payload.token);
  if (String(route && route.status || '').trim().toLowerCase() !== 'active') {
    adminError_('TICKET_INACTIVE');
  }
  var spreadsheet = getEventSpreadsheet_(registry, route.eventId);
  var match = findAttendanceTicket_(spreadsheet, payload.token, route);
  if (match.status !== 'active') adminError_('TICKET_INACTIVE');
  if (String(match.event.status || '').toLowerCase() !== 'live') {
    adminError_('CHECK_IN_CLOSED');
  }
  var sessionId = payload.sessionId.trim();
  var session = match.sessions.filter(function(candidate) {
    return candidate.sessionId === sessionId;
  })[0];
  if (!session) adminError_('SESSION_NOT_REGISTERED');
  var sessionStatus = String(session.status || '').toLowerCase();
  if (sessionStatus !== 'live' && sessionStatus !== 'open') {
    adminError_('CHECK_IN_CLOSED');
  }
  var now = new Date();
  if (!isWithinInternalAttendanceWindow_(registry, session, now)) {
    adminError_('CHECK_IN_CLOSED');
  }
  var duplicate = readRows(spreadsheet, '签到记录').some(function(record) {
    return record.registrationId === match.registrationId &&
      record.sessionId === sessionId &&
      String(record.status || '').toLowerCase() === 'checked_in';
  });
  if (duplicate) adminError_('ALREADY_CHECKED_IN');
  var row = {
    checkInId: Utilities.getUuid(),
    registrationId: match.registrationId,
    eventId: match.event.eventId,
    sessionId: sessionId,
    checkedInAt: now.toISOString(),
    checkedInBy: String(actor || '').trim().toLowerCase(),
    status: 'checked_in'
  };
  var sheet = getRequiredSheet_(spreadsheet, '签到记录');
  var values = normalizeRow_('签到记录', row);
  sheet.getRange(sheet.getLastRow() + 1, 1, 1, values.length).setValues([values]);
  return { status: 'checked_in', sessionId: sessionId, checkedInAt: row.checkedInAt };
}

function isWithinInternalAttendanceWindow_(registry, session, now) {
  var startsAt = Date.parse(session.startsAt);
  var endsAt = Date.parse(session.endsAt);
  if (!isFinite(startsAt) || !isFinite(endsAt) || endsAt <= startsAt) return false;
  var settings = getAdminSettings(registry);
  var attendance = settings && settings.attendance && typeof settings.attendance === 'object'
    ? settings.attendance : {};
  var earlyMinutes = Number(attendance.earlyMinutes);
  var lateMinutes = Number(attendance.lateMinutes);
  if (!isFinite(earlyMinutes) || earlyMinutes < 0) earlyMinutes = 60;
  if (!isFinite(lateMinutes) || lateMinutes < 0) lateMinutes = 60;
  var timestamp = now.getTime();
  return timestamp >= startsAt - earlyMinutes * 60000 &&
    timestamp <= endsAt + lateMinutes * 60000;
}

function switchInternalAdminSheet_(payload, actor) {
  var request = requireAdminObject_(payload);
  if (request.confirm !== true || typeof request.spreadsheetId !== 'string' ||
      !request.spreadsheetId.trim()) {
    adminError_(request.confirm === true ? 'INVALID_REQUEST' : 'CONFIRMATION_REQUIRED');
  }
  var registry = getRegistrySpreadsheet_();
  requireNoSwitchMaintenance_(registry);
  var candidate;
  try {
    candidate = openSpreadsheetById_(request.spreadsheetId);
    validateAdminSpreadsheet_(candidate);
  } catch (error) {
    if (error && error.publicCode) throw error;
    adminError_('SHEET_CONNECTION_FAILED');
  }
  setSharedSettingValue_(registry, ACTIVE_SPREADSHEET_ID, candidate.getId());
  appendAdminAudit_(
    candidate,
    'SWITCH_ACTIVE_SPREADSHEET',
    'spreadsheet',
    'active',
    actor,
    { previousDataRetained: true, migrationPerformed: false }
  );
  return {
    connected: true,
    sheetName: String(candidate.getName ? candidate.getName() : 'Connected'),
    warning: '旧数据会保留在原数据表；系统不会自动迁移。'
  };
}
